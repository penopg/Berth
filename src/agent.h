// Профиль агента: чем занята вкладка и как это запускать.
//
// Профиль — данные, а не код. Добавить Codex или что угодно ещё должно быть
// изменением таблицы, а не правкой цикла и отрисовки. Поэтому здесь нет ни
// одного `if (claude)`: специфика агента живёт в полях.
#ifndef BERTH_AGENT_H
#define BERTH_AGENT_H

#include <stdbool.h>

typedef struct {
    const char *id;         // "shell", "claude", ...
    const char *label;      // как показывать в панели

    // Команда запуска. NULL — просто оболочка пользователя без команды.
    // Строка пишется в pty после старта, как если бы её набрали руками.
    const char *launch;

    // Чем запускать, когда у проекта есть прошлая работа. Смысл в том, чтобы
    // человек не набирал флаги: открыл проект — продолжил с того же места.
    const char *launch_resume;

    // Чем именно продолжать, когда одной команды мало. Claude Code, например,
    // отказывается продолжать сессию, в которой прямо сейчас работает фоновый
    // агент, — и вместо работы человек получает отказ. Профиль остаётся
    // данными: решение принимает модуль самого агента.
    // NULL — берём launch_resume как есть.
    void (*resume_command)(const char *cwd, char *out, size_t cap);

    // Как узнать, есть ли эта прошлая работа. NULL — всегда с чистого листа.
    // Указатель, а не условие по коду: знание про конкретного агента живёт
    // в его модуле, а профиль остаётся данными.
    bool (*has_history)(const char *cwd);

    // Чем чистить контекст, не выходя из агента. NULL — очистить экран.
    const char *clear_context;

    // Умеет ли агент сам сообщать о себе через escape-последовательности
    // (прогресс, метрики). Пока не используется — задел под Этап 3, чтобы
    // не подмешивать знание про конкретного агента в код панели.
    bool reports_progress;
} AgentProfile;

// Встроенные профили. Позже список будет читаться из настроек.
const AgentProfile *agent_default(void);
const AgentProfile *agent_by_id(const char *id);

#endif // BERTH_AGENT_H
