// Таблица проекта на странице: TSV из реестра документов, показанный по
// просьбе человека.
//
// Формат — тот, что заводит скилл berth-data: первая строка заголовки,
// колонки через табуляцию, файл начинается с BOM (его требует Excel).
// BOM здесь срезается: он сидит в начале первой ячейки заголовка и иначе
// уехал бы в подпись колонки.
//
// Таблица читается целиком в память и живёт в наборе проекта. Пределы —
// не экономия, а защита кадра: страница рисует её каждый кадр, и файл на
// сто тысяч строк не должен превращать окно в слайд-шоу. Что не влезло,
// показывается числом: «в файле ещё N записей».
#ifndef BERTH_TABLE_H
#define BERTH_TABLE_H

#include <stdbool.h>
#include <time.h>

// Шестнадцать, а не двенадцать: у таблицы задач Jira двенадцать колонок
// контракта, и первая же своя колонка («киллер-фича») стала тринадцатой —
// берт отбросил её молча, и человек искал её в «Настроить». Цена —
// 120 × 16 × 512 = 983 КБ на таблицу.
#define TABLE_COLS_MAX 16
#define TABLE_ROWS_MAX 120
// Ячейка вмещает и текст, а не только слово: во впечатлениях о фильмах
// живут строки на 236 байт, и при 64 они обрывались на полуслове ещё при
// чтении — раскрытая запись показывала обрубок, откуда его уже не достать.
// Цена — память: 120 × 12 × 512 = 737 КБ на таблицу, две на проект, восемь
// проектов в кэше. Для окна на рабочем столе это ничто.
#define TABLE_CELL_MAX 512   // ~250 знаков кириллицы

typedef struct {
    char path[256];          // как в реестре, относительно корня проекта
    char name[64];           // имя файла без расширения — подпись раздела

    char cols[TABLE_COLS_MAX][TABLE_CELL_MAX];
    int  col_count;
    // Ширина колонки в знаках — по заголовку и всем ячейкам. Считается при
    // чтении: мерить сто двадцать строк каждый кадр незачем, файл меняется
    // куда реже кадра.
    int  col_chars[TABLE_COLS_MAX];
    // Средняя длина непустой ячейки в знаках — по показанной форме. По ней
    // выбирается главная колонка: та, где текст длиннее всех в среднем. Ей
    // достаётся всё место, что осталось от узких, а не те же 24 знака.
    int  col_avg[TABLE_COLS_MAX];
    int  main_col;           // -1, если строк нет
    // Текст главной колонки длинный (в среднем от 60 знаков) — запись идёт
    // в два этажа: узкие колонки строкой, главная под ними во всю ширину.
    // Решается по данным, не настройкой.
    bool two_line;
    // Что показывать и в каком порядке — выбор человека, кнопка
    // «Настроить». Хранится именами в реестре показанного, а не номерами:
    // агент дописывает колонки в середину, и номера поехали бы молча.
    // col_order — порядок показа, перестановка номеров колонок файла.
    bool col_show[TABLE_COLS_MAX];
    int  col_order[TABLE_COLS_MAX];

    // Колонка из одних чисел равняется по правому краю: так видно порядок
    // величины, и глаз сравнивает цифры, а не читает их.
    bool col_num[TABLE_COLS_MAX];

    // Фильтр показа (строка filter в shown.tsv): записи, где колонка пуста
    // (или не пуста), — те, что ждут человека. Остальные складываются.
    int  filter_col;         // -1 — фильтра нет
    bool filter_empty;
    char filter_label[48];
    bool row_pass[TABLE_ROWS_MAX];
    int  pass_count;

    char cells[TABLE_ROWS_MAX][TABLE_COLS_MAX][TABLE_CELL_MAX];
    int  row_count;          // сколько прочитали — последние в файле
    int  file_rows;          // сколько записей в файле
    bool wide;               // колонок в файле больше, чем взяли
    int  file_cols;          // сколько колонок в заголовке файла, включая отброшенные
    bool exists;
    time_t mtime;
} Table;

// Прочитать таблицу. Файла нет или он не разбирается — exists = false.
void table_load(Table *t, const char *cwd, const char *rel);

// Как показать ячейку в списке: по форме значения, а не по имени колонки.
// «2026-09-03 17:30» — «3 сен 17:30», «сегодня 17:30», «вчера 17:30», у
// чужого года без времени; «Имя <адрес>» — «Имя». Остальное как есть.
// Полное значение остаётся в файле и в раскрытой записи.
void table_cell_text(const char *raw, char *out, size_t cap);

// Файл на диске правили — пора перечитать.
bool table_changed(const Table *t, const char *cwd);

// Какие колонки показывать и в каком порядке: имена через «|», в порядке
// показа; имя с «-» впереди — колонка спрятана. Пустая строка или NULL —
// все по порядку файла. Имя, которого в таблице нет, пропускается; не
// совпало ничего — снова все, иначе правка заголовков в файле оставила бы
// пустую таблицу. Колонки, которых в списке нет (агент дописал), встают в
// конец видимыми.
void table_set_cols(Table *t, const char *spec);

// Фильтр показа: колонка по имени и условие. col NULL или незнакомое имя —
// фильтра нет, проходят все. Пересчитывает row_pass и pass_count.
void table_set_filter(Table *t, const char *col, bool empty, const char *label);

// Обратно в строку для записи в реестр. Порядок файла и все колонки на
// виду — пустая строка: это умолчание, и хранить его незачем.
void table_cols_spec(const Table *t, char *out, size_t cap);

#endif // BERTH_TABLE_H
