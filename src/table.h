// Таблица проекта на странице: TSV из реестра документов, показанный по
// просьбе человека.
//
// Формат — тот, что заводит скилл berth-data: первая строка заголовки,
// колонки через табуляцию, файл начинается с BOM (его требует Excel).
// BOM здесь срезается: он сидит в начале первой ячейки заголовка и иначе
// уехал бы в подпись колонки.
//
// Таблица читается целиком в память и живёт в наборе проекта. Пределы —
// не экономия, а защита кадра: страница рисует её каждый кадр, и файл на
// сто тысяч строк не должен превращать окно в слайд-шоу. Что не влезло,
// показывается числом: «в файле ещё N записей».
#ifndef BERTH_TABLE_H
#define BERTH_TABLE_H

#include <stdbool.h>
#include <time.h>

#define TABLE_COLS_MAX 12
#define TABLE_ROWS_MAX 120
#define TABLE_CELL_MAX 64    // ~30 знаков кириллицы

typedef struct {
    char path[256];          // как в реестре, относительно корня проекта
    char name[64];           // имя файла без расширения — подпись раздела

    char cols[TABLE_COLS_MAX][TABLE_CELL_MAX];
    int  col_count;
    // Ширина колонки в знаках — по заголовку и всем ячейкам. Считается при
    // чтении: мерить сто двадцать строк каждый кадр незачем, файл меняется
    // куда реже кадра.
    int  col_chars[TABLE_COLS_MAX];
    // Показывать ли колонку: выбор человека, кнопка «Настроить». Хранится
    // именами в реестре показанного, а не номерами: агент дописывает
    // колонки в середину, и номера поехали бы молча.
    bool col_show[TABLE_COLS_MAX];

    // Колонка из одних чисел равняется по правому краю: так видно порядок
    // величины, и глаз сравнивает цифры, а не читает их.
    bool col_num[TABLE_COLS_MAX];

    char cells[TABLE_ROWS_MAX][TABLE_COLS_MAX][TABLE_CELL_MAX];
    int  row_count;          // сколько прочитали
    int  file_rows;          // сколько записей в файле
    bool wide;               // колонок в файле больше, чем взяли
    bool exists;
    time_t mtime;
} Table;

// Прочитать таблицу. Файла нет или он не разбирается — exists = false.
void table_load(Table *t, const char *cwd, const char *rel);

// Файл на диске правили — пора перечитать.
bool table_changed(const Table *t, const char *cwd);

// Какие колонки показывать: имена через «|». Пустая строка или NULL — все.
// Имя, которого в таблице нет, пропускается; не совпало ничего — снова все,
// иначе правка заголовков в файле оставила бы пустую таблицу.
void table_set_cols(Table *t, const char *spec);

// Обратно в строку для записи в реестр. Показаны все — пустая строка.
void table_cols_spec(const Table *t, char *out, size_t cap);

#endif // BERTH_TABLE_H
