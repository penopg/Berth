// Session — вкладка: проект, агент и терминал под ним.
//
// Разделение с Term намеренное: Term знает про VT и дочерний процесс и ничего
// не знает про проекты, агентов и метрики. Всё, что появится дальше — процент
// контекста, состояние агента, индикаторы — оседает здесь, а не протекает
// в код терминала.
#ifndef BERTH_SESSION_H
#define BERTH_SESSION_H

#include <stdbool.h>

#include "raylib.h"
#include "term.h"
#include "ctx.h"
#include "agent.h"
#include "theme.h"
#include "projinfo.h"

// Вкладок помещается столько. Прежние 16 упирались в живой сценарий: у
// проекта, над которым идёт работа, их бывает десяток, и открыть ещё одну
// вкладку становилось некуда.
#define SESSION_MAX 32
#define SESSION_NAME_MAX 64
#define SESSION_PATH_MAX 512

// Что сейчас с агентом во вкладке. Пока выставляется по жизни процесса;
// на Этапе 3 сюда придут состояния от самого агента.
typedef enum {
    SESSION_STATE_IDLE = 0,   // ждёт ввода
    SESSION_STATE_BUSY,       // работает
    SESSION_STATE_ATTENTION,  // зовёт: bell или уведомление
    SESSION_STATE_DEAD,       // процесс завершился
} SessionState;

// Чем занята вкладка. Страница — свой экран, нарисованный нами: у неё нет ни
// процесса, ни pty. Кнопка на странице проекта превращает её в терминал прямо
// на месте, не плодя соседнюю вкладку.
typedef enum {
    SESSION_KIND_TERM = 0,
    SESSION_KIND_PAGE,
} SessionKind;

// Чем вкладка приходится проекту.
//
// Разговор у проекта один — это MAIN, и второго такого не бывает. Но работа
// рядом с ним нужна: собрать журнал, посмотреть файлы. Это задачи (TASK) —
// они видны, их можно открыть и остановить, и они не занимают собой разговор.
typedef enum {
    SESSION_ROLE_MAIN = 0,   // разговор проекта: контекст плюс агент
    SESSION_ROLE_TASK,       // фоновая работа рядом с разговором
} SessionRole;

typedef enum {
    SESSION_PAGE_PROJECT = 0,
    SESSION_PAGE_SETTINGS,
} SessionPageKind;

typedef struct {
    Term term;

    SessionKind     kind;
    SessionPageKind page;
    SessionRole     role;

    // Открыть ленту на свежем: журнал растёт вниз, и человек приходит за
    // последним, а не за первым днём работы. Высота содержимого известна
    // только после отрисовки, поэтому это флаг на один кадр.
    bool page_scroll_end;

    // Когда дослать Enter после вставки (GetTime), 0 — нечего. Claude Code
    // разбирает длинную вставку не сразу, и Enter, отправленный в том же
    // потоке байтов, пропадает: текст остаётся в поле ввода свёрнутым в
    // «[Pasted text]». Поэтому Enter — отдельное нажатие, чуть позже.
    double enter_due;

    // Когда закрыть вкладку задачи, которая закончилась успешно (GetTime),
    // 0 — не закрывать. Пара секунд, чтобы итог успел мелькнуть, если на
    // вкладку смотрели; упавшая задача остаётся — её надо прочесть.
    double close_due;

    // Что страница должна сказать человеку про его последнее действие.
    // Пусто — говорить нечего. Живёт до следующего действия: страница
    // рисуется каждый кадр, и мигающее сообщение было бы не прочесть.
    char page_notice[120];

    // На сколько прокручена страница. Живёт у вкладки, а не у отрисовки:
    // человек уходит в терминал и возвращается на то же место.
    int page_scroll;

    // Какая задача раскрыта на странице: её номер плюс один, 0 — никакая.
    // Плюс один — чтобы обнулённая вкладка означала «ничего не раскрыто».
    int page_task_open;
    // …и в каком списке: -1 — свои задачи, иначе номер подпроекта.
    int page_task_sub;

    // Какая запись журнала раскрыта: номер плюс один, 0 — никакая.
    int page_journal_open;

    // Какой скилл раскрыт на странице: номер плюс один, 0 — никакой.
    int page_skill_open;

    // Какие разделы подпроектов раскрыты на странице — битами по номеру.
    // По умолчанию свёрнуты: их задачи нужны реже своих.
    unsigned page_subs_open;

    // Показывать страницу поверх работающей вкладки. Процесс при этом жив и
    // читается дальше — просто на экране вместо него карточка проекта.
    bool show_page;

    char name[SESSION_NAME_MAX];    // имя проекта — его показываем в панели
    char cwd[SESSION_PATH_MAX];
    char group[SESSION_NAME_MAX];   // группа проектов; пустая — без группы
    Color color;                    // цвет группы

    // Какой диалог Claude Code ведёт эта вкладка. Пусто у вкладки без агента
    // и пока id не выяснен. Переживает перезапуск в раскладке: без него
    // вкладка после запуска тянет жребий заново и попадает не в свой диалог.
    char session_id[PROJINFO_ID_MAX];

    const AgentProfile *agent;
    const Theme *theme;   // тема проекта: у личных вкладок может быть светлой
    int project;    // индекс в ProjectList, либо -1 для вкладки вне списка

    SessionState state;
    time_t state_since;   // когда состояние менялось в последний раз (из реестра); 0 — неизвестно
    int  progress;   // 0..100 от OSC 9;4, или -1 если не сообщается

    // Остаток контекста разговора: из хвоста jsonl сессии, по времени
    // правки файла. window == 0 — данных нет (разговор ещё пуст).
    CtxInfo ctx;
    time_t  ctx_mtime;
} Session;

typedef struct {
    Session items[SESSION_MAX];
    int      count;
    int      active;    // индекс активной вкладки, -1 если пусто
} SessionList;

// Параметры новой вкладки. Пустые поля заполняются разумными значениями:
// имя — из последнего сегмента пути, каталог — домашний.
typedef struct {
    const char *name;
    const char *cwd;
    const char *group;
    Color color;
    const AgentProfile *agent;
    const Theme *theme;     // NULL — тема по умолчанию
    int project;            // -1, если вкладка не связана с проектом

    // Открыть не терминал, а свой экран. Процесс при этом не запускается.
    SessionKind     kind;
    SessionPageKind page;

    // Задачам инвариант «один разговор на проект» не мешает: их может быть
    // несколько, и живут они, пока делают дело.
    SessionRole     role;

    // Как назвать задачу в панели и на странице: «журнал», «сборка».
    const char     *task_name;

    // Команда, которую напечатать во вкладке при открытии — паспорт проекта.
    // NULL, если печатать нечего.
    const char *brief;

    // Чем занять вкладку вместо обычной команды агента. Через это поле
    // страница открывает выбранную сессию: `claude --resume <id>`.
    const char *command;

    uint16_t cols, rows;
    int cell_width, cell_height;
} SessionOpts;

void session_list_init(SessionList *list);

// Открывает вкладку и делает её активной. Возвращает индекс или -1.
//
// У проекта одна вкладка: если для этого каталога она уже есть, возвращается
// она, а новая не заводится. Прошлые разговоры — это история в журнале, а не
// живые процессы.
int  session_open(SessionList *list, const SessionOpts *opts);

// Разговор этого проекта, либо -1. Задачи не в счёт: они рядом с работой,
// а не вместо неё.
int  session_of_project(const SessionList *list, const char *cwd);

// Закрывает вкладку: гасит процесс и убирает её из списка.
// Активной становится соседняя.
void session_close(SessionList *list, int index);

// Закрывает всё — при выходе из приложения.
void session_close_all(SessionList *list);

void session_activate(SessionList *list, int index);

// Запускает процесс во вкладке, которая была страницей. Возвращает false,
// если терминал открыть не удалось — страница при этом остаётся страницей.
// command — что напечатать вместо обычной команды агента; NULL, чтобы агент
// решал сам (продолжить прошлую работу или начать заново). Через него страница
// продолжает выбранную сессию: `claude --resume <id>`.
bool session_start_term(Session *s, const AgentProfile *agent,
                        uint16_t cols, uint16_t rows,
                        int cell_width, int cell_height,
                        const char *brief, const char *command);

// Перечитывает сведения о проекте (ветка, статус, журнал) с диска.
//
// Сами сведения живут не во вкладке, а в кэше по каталогу (`projstate.h`):
// они принадлежат проекту, и десяти вкладкам одного проекта незачем держать
// десять копий одного журнала.
void session_refresh_info(Session *s);

// Уточняет, в каком диалоге сидит вкладка, спрашивая реестр живых процессов
// Claude Code. Нужно там, где id выбирали не мы: вкладка начала новую сессию
// сама, и её имя знает только Claude Code.
//
// Дорого по меркам кадра (обход каталога и sysctl на процесс), поэтому
// вызывается по событиям — перед сохранением раскладки и при открытии
// страницы, — а не каждый кадр.
void session_track_id(Session *s);

// Когда в разговоре в последний раз что-то делалось: время последнего
// ответа агента из jsonl, а пока его нет — смена состояния в реестре.
// Реестр после перезапуска берта говорит «только что» про всех: процессы
// подняты заново, а работы в них не было.
time_t session_last_work(const Session *s);

// Разговор пуст: файл диалога есть, а ответов агента в нём нет — только
// служебные записи. Работы там не было, и «только что» про него — ложь.
bool session_empty(const Session *s);

// Спит ли разговор: агент свободен дольше `after` секунд. Спящий в панели
// сжимается до одной строки — точка говорит, что он открыт, а больше
// сказать о нём нечего.
bool session_sleeping(const Session *s, time_t now, int after);

// Остаток контекста из jsonl разговора; зовётся из session_track_id.
void session_track_ctx(Session *s);

// Есть ли у вкладки живой процесс. Страница процессом не владеет, и опрашивать
// её терминал нельзя: там нули, а не открытый pty.
static inline bool session_has_term(const Session *s)
{
    return s->kind == SESSION_KIND_TERM;
}

// Что показываем на экране. Вкладка с живым процессом тоже может показывать
// страницу: это её оборотная сторона, а не отдельное окно.
static inline bool session_shows_page(const Session *s)
{
    return s->kind == SESSION_KIND_PAGE || s->show_page;
}

static inline Session *session_active(SessionList *list)
{
    return list->active >= 0 ? &list->items[list->active] : NULL;
}

// Сохранить и восстановить раскладку вкладок.
//
// Процессы перезапуск не переживают, и это нормально: у агентов состояние
// диалога лежит на диске, поэтому восстановленная вкладка сама продолжает
// прошлую работу. Терминалу достаточно помнить, что было открыто.
// extra — строки состояния панели (свёрнутые группы), пишутся перед вкладками.
bool session_save_layout(const SessionList *list, const char *path, const char *extra);

// Кадровый шаг для всех вкладок: вычитать вывод и обновить состояние.
//
// Опрашивать нужно все, а не только активную: фоновая сессия, которую никто
// не читает, упрётся в переполненный буфер pty, и процесс в ней встанет.
void session_poll_all(SessionList *list);
void session_set_theme(Session *s, const Theme *theme);
const char *session_task_state_text(const Session *s);

// Заголовок для панели: то, что сообщил процесс через OSC, иначе имя агента.
const char *session_subtitle(const Session *s);

// Заголовок окна: имя проекта и, если оно что-то добавляет, чем сессия занята.
//
// Брать голый OSC-заголовок нельзя: агент называет окно собой («Claude Code»),
// и окно перестаёт показывать, над каким проектом идёт работа. Имя проекта
// знает терминал, а не программа внутри, — поэтому решаем здесь.
void session_window_title(const Session *s, char *out, size_t cap);

#endif // BERTH_SESSION_H
