// Что берт знает о проекте: сведения с диска и журнал работы.
//
// Это принадлежит проекту, а не вкладке. Раньше и то и другое лежало внутри
// Session, и десять вкладок одного проекта держали десять копий одного и того
// же журнала — 165 КБ каждая, при том что нужна одна и только той вкладке,
// которая сейчас показывает страницу.
//
// Кэш живёт в самом модуле: набор на процесс, а не на вызывающего. Проектов,
// с которыми человек работает одновременно, единицы, поэтому давние наборы
// вытесняются, а не копятся.
#ifndef BERTH_PROJSTATE_H
#define BERTH_PROJSTATE_H

#include <time.h>

#include "projinfo.h"
#include "journal.h"
#include "tasks.h"
#include "skills.h"

typedef struct {
    char     cwd[512];
    ProjInfo info;
    Journal  journal;
    TaskList tasks;
    SkillList skills;
    time_t   touched;   // когда набор последний раз спрашивали
    time_t   journal_mtime;   // .berth/journal.md на момент чтения ленты
} ProjectState;

// Тот же набор, но на запись — для перестановки задач и отметок о
// готовности. Единственное, что берт в проекте меняет сам; всё остальное
// читается с диска, и на запись его не выдают.
ProjectState *projstate_edit(const char *cwd);

// Сведения о проекте: готовые, если уже читали, иначе собранные с диска.
// NULL только если каталог не задан.
const ProjectState *projstate_get(const char *cwd);

// Заглянуть в кэш, ничего не читая: NULL, если проект ещё не открывали.
// Отрисовка ходит только этим путём — разбор истории посреди кадра стоит
// десятки миллисекунд и уронил бы частоту.
const ProjectState *projstate_peek(const char *cwd);

// Перечитать с диска — после работы агента журнал и ветка меняются.
void projstate_reload(const char *cwd);

// Скиллы проекта: каталог, свои, унаследованные от родителя (parent —
// путь родителя у подпроекта, иначе NULL). Перечитываются по mtime папок,
// не чаще раза в пару секунд; force — перечитать сейчас, после своей правки.
const SkillList *projstate_skills(const char *cwd, const char *parent, bool force);

// Заметить правки задач на диске: агент отмечает сделанное прямо в файле.
// Дешёвый опрос — по stat на проект, — зовётся раз в пару секунд.
void projstate_poll(void);

#endif // BERTH_PROJSTATE_H
