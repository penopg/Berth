// Задачи проекта: что предстоит сделать, в том порядке, в каком за это
// браться.
//
// Список живёт в самом проекте, `.berth/tasks.md`, рядом с дневником: он
// уезжает вместе с кодом, читается и правится глазами, и агент дописывает в
// него так же, как в любой файл. Формат нарочно простой:
//
//     ## Название задачи
//     Описание в свободной форме — сколько угодно абзацев.
//
//     ## [?] Сделанная агентом задача — нужно проверить
//
//     ## [x] Сделанная задача
//
// Порядок записей в файле — это и есть порядок задач: перестановка на
// странице переписывает файл. Отдельного поля с приоритетом нет намеренно —
// «что первое» человек показывает рукой, а не числом.
#ifndef BERTH_TASKS_H
#define BERTH_TASKS_H

#include <stdbool.h>
#include <stddef.h>
#include <time.h>

#define TASK_MAX        48
#define TASK_TITLE_MAX  320
// Описание — это ТЗ для агента, а не заметка на полях: в него кладут разбор
// причины, куски кода и ссылки на файлы. Прежние 1600 байт — это 800 русских
// букв, и они кончались на середине мысли. Цена подъёма — память: список
// задач выделен целиком, 48 × 8 КБ ≈ 400 КБ на проект, и столько же в кэше
// каждого из восьми открытых. Для настольного окна это ничто, а нарезать
// описание по абзацам ради экономии — усложнение без повода.
#define TASK_BODY_MAX   8192
#define TASKS_FILE      ".berth/tasks.md"

// Что делать с задачей, когда агент её закончил. Берт сам этого не узнает —
// работа идёт в разговоре, — поэтому наказ едет в тексте задачи, а агент
// правит файл. Отметка «проверить» — середина: задача уходит из очереди, но в
// сделанные её переносит человек, посмотрев на результат.
typedef enum {
    TASK_FINISH_REVIEW = 0,  // отметить `[?]` — сделано, нужно проверить
    TASK_FINISH_DONE,        // сразу `[x]`
    TASK_FINISH_NONE,        // ничего не просить
} TaskFinish;

typedef enum {
    TASK_OPEN = 0,
    TASK_REVIEW,   // агент закончил, человек ещё не смотрел
    TASK_DONE,
} TaskState;

typedef struct {
    char title[TASK_TITLE_MAX];
    char body[TASK_BODY_MAX];   // описание как в файле, с переводами строк
    TaskState state;
} Task;

typedef struct {
    Task items[TASK_MAX];
    int  count;
    bool exists;      // файл есть на диске; без него и раздела на странице нет
    bool partial;     // задач в файле больше, чем помещается

    // Что стояло в файле до первой задачи — заголовок и пояснение. При
    // записи возвращается на место: файл принадлежит человеку, и терять
    // его слова из-за перестановки строк нельзя.
    char preamble[512];

    // Время правки файла при последнем чтении или записи: агент отмечает
    // задачи прямо в файле, и берт должен это заметить.
    time_t mtime;
} TaskList;

void tasks_load(TaskList *t, const char *cwd);
bool tasks_save(const TaskList *t, const char *cwd);

// Переставить задачу с места from на место to; остальные сдвигаются.
void tasks_move(TaskList *t, int from, int to);

// Правил ли файл кто-то с момента нашего последнего чтения или записи.
bool tasks_changed(const TaskList *t, const char *cwd);

// Сколько задач в заданном состоянии.
int  tasks_count_in(const TaskList *t, TaskState state);

// Текст задачи для агента: название, под ним описание, а следом — что
// сделать с задачей в файле, когда она будет закончена. Возвращает длину.
size_t tasks_prompt(const Task *task, TaskFinish finish, char *out, size_t cap);

// Ключ настройки и обратно: review | done | none.
const char *tasks_finish_name(TaskFinish f);
bool        tasks_finish_parse(const char *name, TaskFinish *out);

#endif // BERTH_TASKS_H
