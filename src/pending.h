// Сколько записей таблицы ждут человека — для строки проекта в панели.
//
// Строка `filter` в `.berth/shown.tsv` задаёт, какие записи таблицы не
// разобраны (колонка пуста или не пуста) и как это назвать. Страница по ней
// показывает только такие записи, а панель — их число у имени проекта. Панели
// нужны все проекты, а не восемь из кэша состояний, поэтому счёт идёт
// потоком по файлу, без таблицы в памяти: один stat на проект в опрос,
// чтение только когда файл менялся.
#ifndef BERTH_PENDING_H
#define BERTH_PENDING_H

#include <stddef.h>

// Число записей под фильтром и его подпись («не разобрано»); 0 и пустая
// подпись, если фильтра нет или файла нет. Кэш по каталогу.
int pending_get(const char *cwd, char *label, size_t cap);

#endif // BERTH_PENDING_H
