// Настройки: то, что человек подкручивает под себя и что должно пережить
// перезапуск.
//
// Формат файла — «ключ = значение» построчно, как у конфигов терминалов.
// Такой файл правят руками и чинят глазами; JSON здесь дал бы сериализатор
// ради четырёх полей. Раскладка вкладок лежит отдельно: она состояние машины,
// а не выбор человека, и переживает свою жизнь (`layout.tsv`).
#ifndef BERTH_SETTINGS_H
#define BERTH_SETTINGS_H

#include <stdbool.h>
#include <time.h>

#include "tasks.h"

#define SETTINGS_AGENT_ID_MAX 32

typedef struct {
    int  font_size;
    int  sidebar_width;
    bool sidebar_visible;
    char default_agent[SETTINGS_AGENT_ID_MAX];  // чем открывается проект по клику

    // Тема панели слева (с верхней полосой) — одна на окно, при
    // переключении вкладок не меняется. Тема окна справа — терминал и
    // страницы вкладки: имя встроенной темы или `project` — как у проекта
    // в projects.json, а без неё тема панели.
    char theme_panel[64];
    char theme_window[64];

    // Открывать проект страницей (паспорт, история, кнопки) или сразу агентом.
    bool open_project_page;

    // Что агент делает с задачей из списка, когда закончил её.
    TaskFinish task_finish;

    // Модель для служебных задач берта (журнал, сводка): `--model` у
    // `claude -p`. Пусто — модель Claude Code по умолчанию. Служебной
    // работе дорогая модель не нужна, а лимит она ест наравне с разговором.
    char task_model[64];

    // Показывать ли в свёрнутой группе панели проекты с живой сессией.
    bool collapsed_show_live;

    // Спрашивать ли лимиты у сервера самим, токеном Claude Code из связки
    // ключей. Иначе — только то, что Claude Code сам положил в свой кэш.
    bool usage_fetch;

    // Выключенные скиллы берта, через запятую: `berth-tasks`. Скиллы берта
    // едут с пакетом и включены все; выключенный не раскладывается в папку
    // пакета — и Claude Code его не видит.
    char skills_off[512];

    // Пороги занятого контекста в панели, в процентах окна: от ctx_warn —
    // янтарный, от ctx_crit — красный. По опыту качество на миллионном
    // окне проседает после 200–300k, поэтому по умолчанию 30 и 60, а не
    // «когда почти кончилось».
    int ctx_warn;
    int ctx_crit;

    // Через сколько минут простоя свободный разговор в панели сжимается
    // до одной строки. 0 — никогда.
    int sleep_after;

    // При запуске берт поднимает процессом только разговоры, где работа
    // была за последние resume_within часов; остальные встают страницами,
    // и разговор продолжается по кнопке тем же id. 0 — поднимать все.
    int resume_within;

    // Маркер живого разговора в панели: karateka (по умолчанию) — сценка с
    // каратекой: бой, пока агент работает, победа, поклон, когда зовёт;
    // dot — точка и квадратик. Переменная BERTH_MARKER перекрывает.
    char marker[16];
} Settings;

bool settings_scene_enabled(const Settings *s);

// Включён ли скилл берта с таким именем; и переключить.
bool settings_skill_enabled(const Settings *s, const char *name);
void settings_skill_set(Settings *s, const char *name, bool enabled);

// Значения по умолчанию. Всегда вызывать первым: файла может не быть, и
// половина полей может отсутствовать в существующем.
void settings_defaults(Settings *s);

// Читает файл поверх уже заполненной структуры. Отсутствие файла — не ошибка:
// настроек просто ещё нет. Неизвестные ключи и мусор в значениях молча
// пропускаются, чтобы опечатка не превращалась в пустой экран.
bool settings_load(Settings *s, const char *path);

// Перезаписывает файл целиком, с комментариями-подсказками. Чужие комментарии
// при этом теряются — цена того, что настройки меняются и из интерфейса.
bool settings_save(const Settings *s, const char *path);

// Правил ли файл кто-то снаружи с момента нашего последнего чтения или записи.
bool settings_changed(const char *path);

#endif // BERTH_SETTINGS_H
