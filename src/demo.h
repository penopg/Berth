// Демо-проекты первого запуска.
//
// Пустая панель не рассказывает о продукте ничего: человек видит одну кнопку
// «Добавить группу» и не понимает, что берт умеет. Поэтому при самом первом
// запуске берт показывает себя собой — тремя настоящими проектами в папке
// `~/.config/berth/Демо`.
//
// Это обычные папки с обычными файлами: паспорт, сводка, задачи, дневник,
// таблица, действия, документы. Их можно править, ломать и удалять; группу
// целиком человек скрывает крестиком в панели, а вернуть может в настройках.
//
// Содержимое лежит строками в demo.c, как у встроенных скиллов
// (skills_builtin.c): демо обязано появиться на машине, где нет ничего,
// кроме самого бинаря.
#ifndef BERTH_DEMO_H
#define BERTH_DEMO_H

#include <stdbool.h>
#include <stddef.h>

// Раскладывает демо-проекты в <config>/Демо. Существующие файлы не трогает:
// человек мог их поправить, а мы приходим сюда только на первом запуске.
// Возвращает false, если не удалось создать ни одного файла.
// В out_dir кладётся путь папки-группы, в out_first — путь проекта, который
// стоит открыть первым (может быть NULL, если он не нужен).
bool demo_install(const char *config_dir,
                  char *out_dir, size_t dir_cap,
                  char *out_first, size_t first_cap);

#endif
