// Создаёт всю цепочку каталогов до файла. Существующий каталог не ошибка.
static bool mkdir_parents(const char *file_path)
{
    char buf[1024];
    snprintf(buf, sizeof(buf), "%s", file_path);

    for (char *p = strchr(buf + 1, '/'); p; p = strchr(p + 1, '/')) {
        *p = '\0';
        if (mkdir(buf, 0755) != 0 && errno != EEXIST) return false;
        *p = '/';
    }
    return true;
}

// Существующий файл не трогаем: демо раскладывается один раз, но папка могла
// пережить снос настроек, а правки в ней — человеческие.
static bool write_once(const char *path, const char *text)
{
    struct stat st;
    if (stat(path, &st) == 0) return true;
    if (!mkdir_parents(path)) return false;

    FILE *f = fopen(path, "wb");
    if (!f) return false;
    size_t len = strlen(text);
    bool ok = fwrite(text, 1, len, f) == len;
    fclose(f);
    return ok;
}

// Дневник пишется отдельно: у записи в шапке стоит дата, и «сегодня» честнее
// вшитой даты сборки. Время местное — дневник пишет и читает человек.
static bool write_journal(const char *root)
{
    char path[1024];
    snprintf(path, sizeof(path), "%s/" DEMO_FIRST "/.berth/journal.md", root);

    struct stat st;
    if (stat(path, &st) == 0) return true;

    time_t now = time(NULL);
    time_t began = now - 20 * 60;
    struct tm a, b;
    localtime_r(&began, &a);
    localtime_r(&now, &b);

    char day[32], t1[16], t2[16];
    strftime(day, sizeof(day), "%Y-%m-%d", &a);
    strftime(t1,  sizeof(t1),  "%H:%M",    &a);
    strftime(t2,  sizeof(t2),  "%H:%M",    &b);

    char text[2048];
    snprintf(text, sizeof(text),
        "# Дневник проекта\n"
        "\n"
        "Записи пишет агент по просьбе берта — действие «Обновить журнал» справа\n"
        "в заголовке раздела. Шапку разбирает берт, поэтому её формат жёсткий:\n"
        "дата, время куска, короткий id сессии и заголовок через « · ». Id\n"
        "необязателен; когда он есть, клик по записи поднимает тот самый разговор.\n"
        "\n"
        "## %s %s–%s · Berth завёл демо-проекты\n"
        "Первый запуск: настроек ещё нет, панель пуста, и рассказать о продукте\n"
        "нечем. Берт разложил три демо-проекта в `~/.config/berth/%s` и добавил их\n"
        "группой в панель.\n"
        "\n"
        "Эта запись — пример того, как выглядит итог куска работы: не список\n"
        "реплик, а чем всё кончилось. В ленте под ней видны и реплики человека,\n"
        "и швы сжатия контекста — но реплика, попавшая внутрь готовой записи, из\n"
        "ленты убирается: рекап рассказывает про этот кусок лучше и целиком.\n",
        day, t1, t2, DEMO_GROUP);

    if (!mkdir_parents(path)) return false;
    FILE *f = fopen(path, "wb");
    if (!f) return false;
    size_t len = strlen(text);
    bool ok = fwrite(text, 1, len, f) == len;
    fclose(f);
    return ok;
}

bool demo_install(const char *config_dir,
                  char *out_dir, size_t dir_cap,
                  char *out_first, size_t first_cap)
{
    if (!config_dir || !*config_dir) return false;

    char root[1024];
    snprintf(root, sizeof(root), "%s/%s", config_dir, DEMO_GROUP);
    if (mkdir(root, 0755) != 0 && errno != EEXIST) return false;

    int written = 0;
    for (int i = 0; i < DEMO_FILE_COUNT; i++) {
        char path[1024];
        snprintf(path, sizeof(path), "%s/%s", root, DEMO_FILES[i].path);
        if (write_once(path, DEMO_FILES[i].text)) written++;
    }
    write_journal(root);

    if (written == 0) return false;

    if (out_dir && dir_cap)     snprintf(out_dir, dir_cap, "%s", root);
    if (out_first && first_cap) snprintf(out_first, first_cap, "%s/" DEMO_FIRST, root);
    return true;
}
