// Журнал проекта — что здесь происходило, в хронологии.
//
// Сессия Claude Code — техническая нарезка: компакт, форк и перезапуск режут
// один разговор на файлы, и границы эти человеку ничего не говорят. Журнал
// склеивает их обратно в одну ленту: у каждой записи есть время, и лента
// упорядочена по нему, а не по файлам.
//
// Всё берётся с диска, из тех же jsonl. Ничего не запускается и не
// спрашивается у сети.
#ifndef BERTH_JOURNAL_H
#define BERTH_JOURNAL_H

#include <stdbool.h>
#include <time.h>

#include "projinfo.h"

#define JOURNAL_EVENT_MAX 300
// Реплика человека переносится на экране, поэтому места ей нужно на пару
// строк: прежние 200 байт — это 66 букв кириллицы, обрывок фразы.
#define JOURNAL_TEXT_MAX  400
// Расшифровка идёт на экране в несколько строк, поэтому места ей нужно
// столько, сколько занимают два-три десятка слов кириллицей.
#define JOURNAL_DETAIL_MAX 560

typedef enum {
    JOURNAL_SAID = 0,    // человек написал сам — с этого начинается работа
    JOURNAL_PASTED,      // вставка, картинка, команда: не разговор, а действие
    JOURNAL_COMPACT,     // контекст сжали; дальше работа шла с выжимкой
    JOURNAL_MOVED,       // нить перешла в другой файл
    JOURNAL_RECAP,       // итог куска работы: что сделали и чем кончилось
} JournalKind;

typedef struct {
    time_t      when;
    time_t      until;   // у рекапа — конец куска работы; иначе 0
    JournalKind kind;
    char        session[PROJINFO_ID_MAX];   // где это записано — для продолжения
    char        text[JOURNAL_TEXT_MAX];

    // Расшифровка записи дневника: два-три десятка слов о том, что сделано.
    // Заголовок отвечает «что», расшифровка — «что именно и почему».
    char        detail[JOURNAL_DETAIL_MAX];
} JournalEvent;

typedef struct {
    JournalEvent events[JOURNAL_EVENT_MAX];
    int          count;      // сколько собрано, от старых к новым
    bool         partial;    // событий было больше, показываем хвост
} Journal;

// Файл дневника внутри проекта: его пишет скилл project-journal, а берт
// показывает. Реплики человека рассказывают, с чего работа началась; итог
// её знает только этот файл.
#define JOURNAL_FILE ".berth/journal.md"

// Собирает ленту проекта. Дорого при первом вызове (полный разбор истории),
// дальше дочитывает только дописанное — jsonl растёт с конца и не
// переписывается, поэтому разобранное можно не трогать.
void journal_load(Journal *j, const char *cwd);

// Реплика для разговора проекта: вернуться к записи журнала. Называет
// день и время по-человечески, а для поиска — сессию, файл истории и
// метку времени в UTC, как она записана в jsonl.
void journal_mention(const JournalEvent *ev, const char *cwd, char *out, size_t cap);

// «сегодня», «вчера», «понедельник, 25 августа» — заголовок дня в ленте.
void journal_day(time_t when, char *out, size_t cap);

// «14:32» — время события. Отдельно от дня: у строки в ленте только часы,
// день стоит заголовком над группой.
void journal_clock(time_t when, char *out, size_t cap);

#endif // BERTH_JOURNAL_H
