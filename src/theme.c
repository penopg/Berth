int theme_count(void)
{
    return (int)(sizeof(THEMES) / sizeof(THEMES[0]));
}

const Theme *theme_at(int i)
{
    if (i < 0 || i >= theme_count()) return &THEMES[0];
    return &THEMES[i];
}

const Theme *theme_default(void)
{
    return &THEMES[0];
}

const Theme *theme_find(const char *name)
{
    if (name && *name)
        for (int i = 0; i < theme_count(); i++)
            if (strcmp(THEMES[i].name, name) == 0)
                return &THEMES[i];
    return NULL;
}

const Theme *theme_by_name(const char *name)
{
    const Theme *t = theme_find(name);
    return t ? t : &THEMES[0];
}
