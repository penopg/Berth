// Что терминал знает про Claude Code.
//
// Всё знание об одном конкретном агенте собрано здесь, чтобы профили агентов
// остались таблицей данных, а не набором условий по коду. Для второго агента
// появится такой же модуль рядом.
#ifndef BERTH_CLAUDE_H
#define BERTH_CLAUDE_H

#include <stdbool.h>
#include <stddef.h>

// Каталог, где Claude Code хранит сессии проекта:
// ~/.claude/projects/<путь с заменой / . и пробела на дефис>.
bool claude_session_dir(const char *cwd, char *out, size_t cap);

// Убирает из окружения метки сессии Claude Code.
//
// Терминал часто запускают из-под самого Claude Code, и тогда вкладки
// наследуют метки его сессии: вложенный агент считает себя дочерней сессией и
// перестаёт сохранять историю диалога. Вкладка — самостоятельная сессия, а не
// продолжение того процесса, который открыл окно.
//
// Настройки (ANTHROPIC_*, CLAUDE_CONFIG_DIR) не трогаем: они про то, как
// работать, а не про то, кто кого запустил.
void claude_clear_session_env(void);

// Папка со скиллами берта: <config>/bundle/.claude/skills/berth-*. Это
// часть пакета — лежит в бинаре и раскладывается сюда при каждом запуске,
// перезаписывая своё. Подключается к каждому запуску claude флагом
// --add-dir: Claude Code читает .claude/skills из таких папок, а в личную
// папку и в проекты берт ничего не пишет. Скилл про задачи берта нужен
// только там, где есть берт, — claude из чужого терминала его не видит.
const char *claude_bundle_dir(void);
// off — выключенные через запятую (Settings.skills_off): их папки из
// пакета убираются, и Claude Code их не видит — работающие сессии тоже,
// он следит за папками скиллов на лету.
void claude_install_bundle(const char *off);

// Команда запуска с подключённой папкой берта: «claude …» превращается в
// «claude --add-dir '<папка>' …». Чужие команды (оболочка) не трогаются.
void claude_with_bundle(const char *cmd, char *out, size_t cap);

// Есть ли у проекта прошлые сессии — то есть можно ли продолжить диалог,
// а не начинать с чистого листа.
bool claude_has_history(const char *cwd);

#endif // BERTH_CLAUDE_H
