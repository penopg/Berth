#!/usr/bin/env bash
# Запуск свежей сборки рядом с работающим экземпляром.
#
# Терминал дорабатывают, сидя в нём же, поэтому перезапускать рабочее окно с
# живыми сессиями нельзя. Здесь собирается новая версия и запускается вторым
# окном с меткой в заголовке; старое окно продолжает работать.
#
# Бинарь копируется под своим именем: build.sh подменяет файл переименованием,
# и запущенный экземпляр не пострадает, но отдельная копия делает это явным.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
"$ROOT/build.sh"

DEV_BIN="$ROOT/build/berth-dev"
# Подменяем переименованием, а не cp поверх: cp пишет в тот же inode, и
# запущенный экземпляр получает чужие страницы кода — macOS убивает его с
# «Code Signature Invalid», а следующие запуски того же файла падают в main,
# пока ядро помнит испорченную подпись. rename даёт новый inode: старый
# процесс доживает на старом файле, новый стартует с чистого.
cp -f "$ROOT/build/berth" "$DEV_BIN.new"
mv -f "$DEV_BIN.new" "$DEV_BIN"

BERTH_LABEL="${BERTH_LABEL:-dev}" exec "$DEV_BIN" "$@"
